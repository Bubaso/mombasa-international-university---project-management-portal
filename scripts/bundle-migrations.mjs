/**
 * Concatenates the migrations into one file you can paste into the Supabase
 * SQL editor.
 *
 * `supabase db push` is the normal way and this is not a replacement for it.
 * It exists for the case where the CLI cannot be used at all — an account
 * without the privileges to read the project's settings, no way to open a
 * Postgres connection from wherever you are — and the dashboard, which is
 * plain HTTPS, is the only route left.
 *
 * The output is generated from the migrations every time rather than kept in
 * the repository, because a second copy of the schema is a second thing to
 * forget to update.
 *
 * The whole file runs as one transaction, so a failure part-way leaves
 * nothing behind. That is the point: a half-applied schema is the hardest
 * state to diagnose, because every policy raises and none of it looks like a
 * migration problem from outside.
 *
 * Usage:
 *   node scripts/bundle-migrations.mjs            # everything
 *   node scripts/bundle-migrations.mjs --from 4   # 0004 onwards
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const migrationsDir = join(root, 'supabase', 'migrations');

const fromIndex = process.argv.indexOf('--from');
const from = fromIndex >= 0 ? Number(process.argv[fromIndex + 1]) : 1;
if (!Number.isFinite(from)) throw new Error('--from takes a number, e.g. --from 4');

const all = readdirSync(migrationsDir)
  .filter((name) => /^\d{4}_.*\.sql$/.test(name))
  .sort();

const selected = all.filter((name) => Number(name.slice(0, 4)) >= from);
if (selected.length === 0) throw new Error(`No migrations at or after ${from}`);

const parts = [
  '-- Generated by scripts/bundle-migrations.mjs. Do not edit; regenerate.',
  '--',
  `-- ${selected.length} migration(s): ${selected[0]} … ${selected[selected.length - 1]}`,
  '--',
  '-- Paste the whole thing into the Supabase SQL editor and run it once. It is',
  '-- a single transaction: if anything fails, nothing is applied, and the error',
  '-- names the statement that stopped it.',
  '',
  'begin;',
  '',
];

for (const name of selected) {
  parts.push(
    `-- ${'='.repeat(73)}`,
    `-- ${name}`,
    `-- ${'='.repeat(73)}`,
    '',
    readFileSync(join(migrationsDir, name), 'utf8').trimEnd(),
    '',
  );
}

// So a later `supabase db push` knows these are in and does not start again
// from the top. Separated below the schema on purpose: if this block is the
// thing that fails, the schema above it is still what matters.
const versions = all.map((name) => name.slice(0, 4));
parts.push(
  `-- ${'='.repeat(73)}`,
  '-- Migration history, for the CLI',
  `-- ${'='.repeat(73)}`,
  '--',
  '-- Records every migration in this repository as applied, including the ones',
  '-- that were already in before this file ran. Without it `supabase db push`',
  '-- reads an empty history and tries to apply 0001 again.',
  '--',
  '-- If this block errors, drop it and run the rest: it affects what the CLI',
  '-- believes, not what the database contains.',
  '',
  'create schema if not exists supabase_migrations;',
  'create table if not exists supabase_migrations.schema_migrations (',
  '  version text primary key',
  ');',
  '',
  'insert into supabase_migrations.schema_migrations (version)',
  `select v from unnest(array[${versions.map((v) => `'${v}'`).join(', ')}]) as t(v)`,
  'on conflict (version) do nothing;',
  '',
  'commit;',
  '',
);

const outDir = join(root, 'supabase', 'bundled');
mkdirSync(outDir, { recursive: true });
const target = join(outDir, `migrations-${selected[0].slice(0, 4)}-onwards.sql`);
writeFileSync(target, parts.join('\n'), 'utf8');

const kb = (Buffer.byteLength(parts.join('\n'), 'utf8') / 1024).toFixed(0);
console.log(`${selected.length} migration(s) → ${target} (${kb} KB)`);
for (const name of selected) console.log(`  ${name}`);
